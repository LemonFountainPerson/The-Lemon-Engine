int WorldCameraControl(World *GameWorld, Camera *inputCamera)
{
	if (GameWorld == NULL || inputCamera == NULL || GameWorld->GameState == EMPTY_GAME)
	{
		return MISSING_DATA;
	}

	if (GameWorld->GameState == LOADING)
	{
		return ACTION_DISABLED;
	}


	// Control latching/buffering
	switch(inputCamera->CameraMode)
	{
		case MENU_CAMERA:
		{
			if (inputCamera->CameraLatch == 0)
			{
				inputCamera->CameraXBuffer = inputCamera->CameraX;
				inputCamera->CameraYBuffer = inputCamera->CameraY;
				inputCamera->CameraX = -32000.0;
				inputCamera->CameraY = 0;
				inputCamera->CameraLatch = 1;
			}
		} break;

		default:
		{
			if (inputCamera->CameraLatch == 1)
			{
				inputCamera->CameraX = inputCamera->CameraXBuffer;
				inputCamera->CameraY = inputCamera->CameraYBuffer;
				inputCamera->CameraLatch = 0;
			}
		} break;
	}


	// Move camera
	switch(inputCamera->CameraMode)
	{
		case FOLLOW_PLAYER:
		{
			PhysicsRect *PlayerBox = GameWorld->Player.PlayerBox;

			if (PlayerBox == NULL)
			{
				inputCamera->CameraMode = FREE_ROAM_RESTRICTED;
				return MISSING_DATA;
			}

			float xDifference = PlayerBox->xPos - inputCamera->CameraX;

			inputCamera->CameraX += (xDifference / 5.0);

			if (fabs(xDifference) < 1)
			{
				inputCamera->CameraX = PlayerBox->xPos;
			}
			

			float yOffset = PlayerBox->yPos - inputCamera->CameraY;

			if (yOffset >= (screenHeight * 0.1))
			{
				float difference = yOffset - (screenHeight * 0.1);

				inputCamera->CameraY += (difference / 5.0);

				if (fabs(difference) < 5)
				{
					inputCamera->CameraY = PlayerBox->yPos - (screenHeight * 0.1);
				}
			}
			else if (yOffset < (screenHeight * -0.2))
			{
				float difference = yOffset + (screenHeight * 0.2);

				inputCamera->CameraY += (difference / 5.0) + 1;

				if (fabs(difference) < 5)
				{
					inputCamera->CameraY = PlayerBox->yPos + (screenHeight * 0.2);
				}
			}

			restrictCameraToBounds(inputCamera);
		} break;


		case FREE_ROAM_RESTRICTED:
		{
			restrictCameraToBounds(inputCamera);
		} break;


		default:
		break;
	}


	return LEMON_SUCCESS;
}

int restrictCameraToBounds(Camera *inputCamera)
{
	if (inputCamera == NULL)
	{
		return MISSING_DATA;
	}

	if (inputCamera->maxCameraX < inputCamera->minCameraX + screenWidth)
	{
		inputCamera->maxCameraX = inputCamera->minCameraX + screenWidth;
	}

	if (inputCamera->maxCameraY < inputCamera->minCameraY + screenHeight)
	{
		inputCamera->maxCameraY = inputCamera->minCameraY + screenHeight;
	}


	inputCamera->CameraX = fClamp(inputCamera->CameraX, inputCamera->minCameraX, inputCamera->maxCameraX - screenWidth);
	inputCamera->CameraY = fClamp(inputCamera->CameraY, inputCamera->minCameraY, inputCamera->maxCameraY - screenWidth);

	return LEMON_SUCCESS;
}


int drawObjects(Camera inputCamera, World *GameWorld, RenderFrame ScreenData)
{
	if (GameWorld == NULL || GameWorld->ObjectList == NULL || ScreenData.Renderer == NULL)
	{
		return MISSING_DATA;
	}

	if (RenderSettings.drawSprites == 0)
	{
		return ACTION_DISABLED;
	}

	SDL_Renderer *Screen = ScreenData.Renderer;
	Object *currentObject = NULL;
	int result = LEMON_SUCCESS;

	float oldScaleX = 1.0;
	float oldScaleY = 1.0;
	SDL_GetRenderScale(Screen, &oldScaleX, &oldScaleY);

	float renderRatioX = oldScaleX / ScreenData.zoomX;
	float renderRatioY = oldScaleY / ScreenData.zoomY;

	Camera hudCam = {0};

	for (Layer drawLayer = BACKGROUND; drawLayer < LAYER_COUNT; drawLayer++)
	{
		currentObject = GameWorld->ObjectList->firstObject;

		if (drawLayer == HUD)
		{
			SDL_SetRenderScale(Screen, renderRatioX, renderRatioY);

			while(currentObject != NULL)
			{
				if (drawLayer != currentObject->layer)
				{
					currentObject = currentObject->nextObject;
					continue;
				}

				result = renderObjectSprite(hudCam, *(currentObject->ObjectDisplay), *(currentObject->ObjectBox), Screen);
						
				currentObject = currentObject->nextObject;
			}

			SDL_SetRenderScale(Screen, oldScaleX, oldScaleY);
		}
		else
		{
			while(currentObject != NULL)
			{
				if (drawLayer != currentObject->layer)
				{
					currentObject = currentObject->nextObject;
					continue;
				}

				result = renderObjectSprite(inputCamera, *(currentObject->ObjectDisplay), *(currentObject->ObjectBox), Screen);				
			
				currentObject = currentObject->nextObject;
			}
		}

	}
	
	return LEMON_SUCCESS;
}


int drawHitboxes(Camera inputCamera, World *GameWorld, RenderFrame ScreenData)
{
	if (GameWorld == NULL || GameWorld->ObjectList == NULL || ScreenData.Renderer == NULL)
	{
		return MISSING_DATA;
	}

	if (RenderSettings.drawHitboxes == 0)
	{
		return ACTION_DISABLED;
	}

	SDL_Renderer *Screen = ScreenData.Renderer;
	Object *currentObject = GameWorld->ObjectList->firstObject;
	Camera hudCamera = {0};

	float oldScaleX = 1.0;
	float oldScaleY = 1.0;
	SDL_GetRenderScale(Screen, &oldScaleX, &oldScaleY);
	float renderRatioX = oldScaleX / ScreenData.zoomX;
	float renderRatioY = oldScaleY / ScreenData.zoomY;

	while(currentObject != NULL)
	{
		if (currentObject->layer == HUD)
		{
			SDL_SetRenderScale(Screen, renderRatioX, renderRatioY);

			renderHitbox(hudCamera, GameWorld, currentObject->ObjectBox, Screen);

			SDL_SetRenderScale(Screen, oldScaleX, oldScaleY);
		}
		else
		{
			renderHitbox(inputCamera, GameWorld, currentObject->ObjectBox, Screen);
		}
		
		currentObject = currentObject->nextObject;
	}

	drawPlayerHitboxes(GameWorld->MainCamera, GameWorld, Screen);


	return LEMON_SUCCESS;
}


int renderHitbox(Camera inputCamera, World *gameWorld, PhysicsRect *inputBox, SDL_Renderer *Screen)
{
	if (inputBox == NULL)
	{
		return MISSING_DATA;
	}

	uint32_t colour = colourMap[inputBox->solid % 32];

	SDL_SetRenderDrawColor(Screen, (colour & 0x00FF0000) >> 16, (colour & 0x0000FF00) >> 8, (colour & 0x000000FF), 0xFF);
	
	SDL_FRect Hitbox;

	Hitbox.x = floor((float)((screenWidth >> 1) + inputBox->xPos - inputCamera.CameraX));
	Hitbox.y = floor((float)((screenHeight >> 1) - inputBox->yPos + inputCamera.CameraY - inputBox->ySize));
	Hitbox.h = (float)inputBox->ySize;

	if (DebugSettings.HitboxOutlineThickness > 99)
	{
		Hitbox.w = (float)inputBox->xSize;
		SDL_RenderFillRect(Screen, &Hitbox);
		return EXECUTION_UNNECESSARY;
	}

	Hitbox.w = (float)clamp(DebugSettings.HitboxOutlineThickness, 0, inputBox->xSize);

	SDL_RenderFillRect(Screen, &Hitbox);

	Hitbox.x += (float)(inputBox->xSize - clamp(DebugSettings.HitboxOutlineThickness, 0, inputBox->xSize));
	SDL_RenderFillRect(Screen, &Hitbox);

	Hitbox.x = floor((float)((screenWidth >> 1) + inputBox->xPos - inputCamera.CameraX));
	Hitbox.w = (float)inputBox->xSize;
	Hitbox.h = (float)clamp(DebugSettings.HitboxOutlineThickness, 0, inputBox->ySize);
	SDL_RenderFillRect(Screen, &Hitbox);

	Hitbox.y += (float)(inputBox->ySize - clamp(DebugSettings.HitboxOutlineThickness, 0, inputBox->ySize));
	SDL_RenderFillRect(Screen, &Hitbox);

	return LEMON_SUCCESS;
}


