int DisplaySoundChannelDebugInfo(ChannelName channel)
{
	if (channel < 0 || channel >= CHANNEL_COUNT)
	{
		return INVALID_DATA;
	}

	SoundInstance *currentSound;
	currentSound = SoundChannels[channel].firstSound;
	int i = 0;
	char buffer[DEBUG_TEXT_MAX_LENGTH] = {0};

	sprintf(buffer, "Channel ID: %d  Channel vol: %.2f  \nSound Count: %d/%d", 
		channel, SoundChannels[channel].channelVolume, SoundChannels[channel].soundCount, EngineSettings.MaxSoundsPerChannel);
	AddDebugText(buffer, SCREEN_SOUND_FORMAT, 350, i, 0);

	i += 2;

	while (currentSound != NULL && i < EngineSettings.MaxSoundsPerChannel - 2)
	{
		sprintf(buffer, "%s  Volume: %.2f", currentSound->name, currentSound->volume);
		AddDebugText(buffer, SCREEN_SOUND_FORMAT, 180 + (10 * strlen(currentSound->name)), i, 0);

		currentSound = currentSound->nextSound;
		i++;
	}

	return LEMON_SUCCESS;
}


int AddDebugText(char inputPhrase[], DebugTextFormatting format, int x, int y, int TicksToDelete)
{
	if (inputPhrase == NULL || strlen(inputPhrase) < 1 || strlen(inputPhrase) >= DEBUG_TEXT_MAX_LENGTH)
	{
		return INVALID_DATA;
	}

	int index = 0;

	DebugText *TextsArray = DebugSettings.DebugTexts; 

	while (index < MAX_DEBUG_TEXTS && TextsArray[index].Text != NULL)
	{
		index++;
	}

	if (index >= MAX_DEBUG_TEXTS)
	{
		return -1;
	}

	static TTF_Font *font = NULL;
	if (font == NULL)
	{
		font = TTF_OpenFontIO(SDL_IOFromConstMem(tiny_ttf, tiny_ttf_len), true, 18.0f);
	
		if (font == NULL)
		{ 
	    	putConsoleString("\nFailed to load font!\n");
	    	DebugSettings.DebugTextDisplayMode = DEBUG_TEXT_DISABLED;
	    	return LEMON_ERROR;
		}
	}

    SDL_Surface *text = TTF_RenderText_Blended_Wrapped(font, inputPhrase, 0, DebugSettings.DebugTextColour, 0);

    TextsArray[index].Text = SDL_CreateTextureFromSurface(ScreenData.Renderer, text);
    TextsArray[index].deletionTick = TicksToDelete;
    
    TextsArray[index].CameraRelative = (format == CAMERA_RELATIVE);

    if (format == SCREEN_LIST_FORMAT)
    {
    	TextsArray[index].Location.y = (float)(index + 1) * 20;
    	TextsArray[index].Location.x = (float)(screenWidth >> 1) + x;
    }
    else if (format == SCREEN_SOUND_FORMAT)
    {
    	TextsArray[index].Location.y = (float)50 + (y * 20);
    	TextsArray[index].Location.x = (float)screenWidth - x;
    }
    else
    {
    	TextsArray[index].Location.x = (float)(screenWidth >> 1) + x;
    	TextsArray[index].Location.y = (float)(screenHeight >> 1) - y;
    }

    TextsArray[index].Location.w = text->w;
    TextsArray[index].Location.h = text->h;

	return index;
}


int RemoveDebugText(int index)
{
	DebugText *TextsArray = DebugSettings.DebugTexts; 

	if (TextsArray[index].Text == NULL || index < 0 || index >= MAX_DEBUG_TEXTS)
	{
		return EXECUTION_UNNECESSARY;
	}

	SDL_DestroyTexture(TextsArray[index].Text);
	TextsArray[index].Text = NULL;


	return LEMON_SUCCESS;
}


int RemoveAllDebugTexts()
{
	int i = 0;
	while (i < MAX_DEBUG_TEXTS)
	{
		RemoveDebugText(i);
		i++;
	}

	return LEMON_SUCCESS;
}


int RenderDebugText(World *GameWorld, RenderFrame ScreenData)
{
	int i = 0;
	SDL_Texture *TextPtr = NULL;
	SDL_FRect CorrectedDestination = {0};

	DebugText *TextsArray = DebugSettings.DebugTexts; 

	while (i < MAX_DEBUG_TEXTS)
	{
		if (TextsArray[i].Text != NULL)
		{
			TextPtr = TextsArray[i].Text;
			CorrectedDestination = TextsArray[i].Location;

			if (TextsArray[i].CameraRelative == true)
			{
				CorrectedDestination.x -= GameWorld->MainCamera.CameraX;
				CorrectedDestination.y += GameWorld->MainCamera.CameraY;
			}

			SDL_RenderTexture(ScreenData.Renderer, TextPtr, NULL, &CorrectedDestination);

			TextsArray[i].deletionTick--;
			if (TextsArray[i].deletionTick < 1)
			{
				RemoveDebugText(i);
			}
		}

		i++;
	}


	return LEMON_SUCCESS;
}



