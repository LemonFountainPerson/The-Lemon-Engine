int renderObjectSprite(Camera inputCamera, DisplayData inputData, PhysicsRect inputBox, SDL_Renderer *Screen)
{
	// WARNING! The render pipeline is really messy and not easy to read: All variations of rendering has its own copy of the
	// main render loop, even extremely similar ones. This was done to squeeze out performance (at the expense of a bit of memory)
	// As such, readability was sacrificed somewhat. Continue at your own risk!
	if (inputData.hidden || inputData.RenderModeOverride == DO_NOT_RENDER)
	{
		return ACTION_DISABLED;
	}


	// Prepare data pointers
	Sprite *spritePtr = inputData.spriteBuffer;


	// Decide how to render
	RenderMode inputRenderMode = inputData.RenderModeOverride;

	if (inputRenderMode == DEFAULT_TO_SPRITE)
	{
		inputRenderMode = spritePtr->RenderMode;
	}

	if (inputData.transparencyEffect < 1.0)	// Hijack render mode if transparency effect is being applied so that faster render function can be used when no transparency is applied
	{
		switch (inputRenderMode)
		{
			case SINGLE:
			inputRenderMode = SINGLE_FULL_ALPHA;
			break;

			case TILE:
			inputRenderMode = TILE_FULL_ALPHA;
			break;

			case SCALE:
			inputRenderMode = SCALE_FULL_ALPHA;
			break;

			default:
			break;
		}
	}


	// Locate object on screen
	float realXOffset = (screenWidth >> 1) + inputBox.xPos + inputData.spriteXOffset - inputCamera.CameraX;
	float realYOffset = (screenHeight >> 1) - inputBox.yPos - inputData.spriteYOffset + inputCamera.CameraY - inputBox.ySize;
	double renderDirection = inputData.direction;

	if (inputData.frameBuffer != NULL && inputData.currentAnimation > 0)
	{
		realXOffset += inputData.frameBuffer->SpriteXOffset;
		realYOffset += inputData.frameBuffer->SpriteYOffset;
		renderDirection += inputData.frameBuffer->rotation;
	}

	float xOffset2 = realXOffset + inputBox.xSize;
	float yOffset2 = realYOffset + inputBox.ySize;

	if (inputRenderMode == TILE || inputRenderMode == TILE_FAST || inputRenderMode == TILE_FULL_ALPHA)
	{
		goto Skip_Render_Effects;
	}

	float centerX = realXOffset + (inputBox.xSize >> 1);
	float centerY = realYOffset + (inputBox.ySize >> 1);

	if (inputRenderMode == SINGLE || inputRenderMode == SINGLE_FAST || inputRenderMode == SINGLE_FULL_ALPHA)
	{
		inputBox.xSize = spritePtr->width;
		inputBox.ySize = spritePtr->height;
	}

	if (inputData.size > 0.00001 && fabs(inputData.size - 1.0) > 0.0001)	// Modify box size/pos and rendermode if size value is set to a non 1.0 value
	{
		inputBox.xSize = (int)(inputBox.xSize * inputData.size);
		inputBox.ySize = (int)(inputBox.ySize * inputData.size);

		inputBox.xPos = (float)(centerX - (inputBox.xSize >> 1));
		inputBox.yPos = (float)(centerY - (inputBox.ySize >> 1));	

		inputRenderMode = SCALE;				
	}


	realXOffset = centerX - (inputBox.xSize >> 1);
	realYOffset = centerY - (inputBox.ySize >> 1);
	xOffset2 = realXOffset + inputBox.xSize;
	yOffset2 = realYOffset + inputBox.ySize;

	Skip_Render_Effects:


	if (realXOffset >= screenWidth || xOffset2 < 0 || yOffset2 < 0 || realYOffset >= screenHeight || realXOffset >= xOffset2 || realYOffset >= yOffset2)
	{
		return INVALID_DATA;
	}


	SDL_FRect renderBox;
	renderBox.x = (float)realXOffset;
	renderBox.y = (float)realYOffset;
	renderBox.w = (float)inputBox.xSize;
	renderBox.h = (float)inputBox.ySize;

	SDL_FRect spriteBox;
	spriteBox.x = 0.0;
	spriteBox.y = 0.0;
	spriteBox.w = (float)spritePtr->width;
	spriteBox.h = (float)spritePtr->height;

	SDL_FRect *spriteBoxPtr = &spriteBox;
	
	if (inputRenderMode == SCALE || inputRenderMode == SCALE_FULL_ALPHA)
	{
		spriteBoxPtr = NULL;
	}

	SDL_FlipMode flip = SDL_FLIP_NONE;

	if (inputBox.xFlip == -1)
	{
		flip = SDL_FLIP_HORIZONTAL;
	}

	if (inputBox.yFlip == -1)
	{
		flip = flip | SDL_FLIP_VERTICAL;
	}

	if (inputRenderMode == TILE || inputRenderMode == TILE_FAST || inputRenderMode == TILE_FULL_ALPHA)
	{
		int modPixelY = modulo(inputData.pixelYOffset, spritePtr->height);
		spriteBox.x = (float)inputData.pixelXOffset;
		spriteBox.y = (float)modulo((spritePtr->height - inputBox.ySize - modPixelY), spritePtr->height);
		spriteBox.w = (float)spritePtr->width - spriteBox.x;
		spriteBox.h = (float)spritePtr->height - modPixelY;

		SDL_RenderTextureTiled(Screen, spritePtr->texture, spriteBoxPtr, inputData.size, &renderBox);
	}
	else if (renderDirection != RADIAN_90)
	{
		double rotation = (inputBox.xFlip == -1 ? (RADIAN_90 - renderDirection) : (renderDirection - RADIAN_90)) * RADIAN_TO_DEGREE_PI;
		SDL_RenderTextureRotated(Screen, spritePtr->texture, spriteBoxPtr, &renderBox, rotation, NULL, flip);
	}
	else
	{
		SDL_RenderTextureRotated(Screen, spritePtr->texture, spriteBoxPtr, &renderBox, 0.0, NULL, flip);
	}
	

	return LEMON_SUCCESS;
}


int renderBackGroundSprite(Camera inputCamera, BackgroundData WorldBackground, RenderFrame ScreenData)
{
	if (ScreenData.Renderer == NULL || WorldBackground.BackgroundSpriteBuffer == NULL)
	{ 
		return MISSING_DATA;
	}

	SDL_Renderer *Screen = ScreenData.Renderer;
	RenderMode bgRenderMode = WorldBackground.BackgroundRenderMode;

	if (bgRenderMode == DEFAULT_TO_SPRITE)
	{
		bgRenderMode = WorldBackground.BackgroundSpriteBuffer->RenderMode;
	}

	if (RenderSettings.drawBackGround == 0)
	{
		return ACTION_DISABLED;
	}

	
	Sprite *backGround = WorldBackground.BackgroundSpriteBuffer;
	SDL_FRect renderTarget;

	switch (bgRenderMode)
	{
	case STATIC_BACKGROUND:
		SDL_RenderTexture(Screen, backGround->texture, NULL, NULL);
		break;

	case SINGLE_BACKGROUND:
		renderTarget.w = (float)backGround->width;
		renderTarget.h = (float)backGround->height;
		renderTarget.x = ((screenWidth >> 1) / ScreenData.zoomX) - inputCamera.CameraX * WorldBackground.bgParallax - (backGround->width >> 1);
		renderTarget.y = inputCamera.CameraY * WorldBackground.bgParallax + ((screenHeight >> 1) / ScreenData.zoomY) - (backGround->height >> 1);

		SDL_RenderTexture(Screen, backGround->texture, NULL, &renderTarget);
		break;

	case TILE_BACKGROUND:
		renderTarget.w = (float)screenWidth * 2 / ScreenData.zoomX;
		renderTarget.h = (float)screenHeight * 2 / ScreenData.zoomY;
		renderTarget.x = (float)modulo(((screenWidth >> 1) / ScreenData.zoomX) - inputCamera.CameraX * WorldBackground.bgParallax - (backGround->width >> 1), backGround->width) - backGround->width;
		renderTarget.y = (float)modulo(inputCamera.CameraY * WorldBackground.bgParallax + ((screenHeight >> 1) / ScreenData.zoomY) - (backGround->height >> 1), backGround->height) - backGround->height;

		SDL_RenderTextureTiled(Screen, backGround->texture, NULL, 1.0, &renderTarget);
		break;

	default:
		break;
	}


	return LEMON_SUCCESS;
}


// Debug text functions
int DisplayDebugInfo(World *GameWorld, DebugTextMode debugTextMode)
{
	if (GameWorld == NULL || GameWorld->ObjectList == NULL)
	{
		return MISSING_DATA;
	}

	char text[DEBUG_TEXT_MAX_LENGTH] = {0};

	if (DebugSettings.ObjectCount != 0)
	{
		sprintf(text, "Object Count: %d", GameWorld->ObjectList->objectCount);
		AddDebugText(text, SCREEN_LIST_FORMAT, 16 - (screenWidth >> 1), 0, 0);
	}

	if (DebugSettings.PauseStatus != 0)
	{
		if (DebugSettings.PauseEngine == 1)
		{
			strcpy(text, "Pause Status: Paused");
		}
		else
		{
			strcpy(text, "Pause Status: UnPaused");
		}

		AddDebugText(text, SCREEN_LIST_FORMAT, 16 - (screenWidth >> 1), 0, 0);
	}

	DisplaySoundChannelDebugInfo(DebugSettings.SoundInfo - 1);


	if (DebugSettings.CutsceneInfo)
	{
		sprintf(text, "CutsceneID: %d", GameWorld->CurrentCutscene);
		AddDebugText(text, SCREEN_LIST_FORMAT, 16 - (screenWidth >> 1), 0, 0);
	}


	/* Backgrounds
	if (DebugSettings.BackgroundInfo == 1)
	{
		sprintf(text, "Background sprite Name: %s  Background Sprite ID: %d", );
		AddDebugText(text, SCREEN_RELATIVE, -140, (screenHeight >> 1), 0);
	}
	*/

	// Camera Information
	switch (DebugSettings.CameraInfo)
	{
	case 1:
		sprintf(text, "Camera X: %.2f  Camera Y: %.2f", GameWorld->MainCamera.CameraX, GameWorld->MainCamera.CameraY);
		AddDebugText(text, SCREEN_RELATIVE, -140, (screenHeight >> 1), 0);
		break;

	case 2: 
		sprintf(text, "Camera X: %.2f  Camera Y: %.2f \nCameraLatch: %d \nBuffer X: %.2f  Buffer Y: %.2f", 
			GameWorld->MainCamera.CameraX, GameWorld->MainCamera.CameraY, GameWorld->MainCamera.CameraLatch, GameWorld->MainCamera.CameraXBuffer, GameWorld->MainCamera.CameraYBuffer);
		AddDebugText(text, SCREEN_RELATIVE, -140, (screenHeight >> 1), 0);
		break;

	default:
		break;
	}


	Object *currentObject = GameWorld->ObjectList->firstObject;
	int objCount = GameWorld->ObjectList->objectCount;

	switch(debugTextMode)
	{
		case DEBUG_TEXT_DISABLED:
		case DEBUG_TEXT_ENABLED:
			break;

		case ONLY_PLAYER_INFO:
		{
			while (currentObject != NULL && objCount > 0 && GameWorld->Player.PlayerPtr != currentObject)
			{			
				currentObject = currentObject->nextObject;
				objCount--;
			}

			DisplayObjectDebugInfo(currentObject, objCount, GameWorld);
		} break;

		case ONLY_NONSTATIC_OBJECT_INFO:
		{
			while (currentObject != NULL && objCount > 0)
			{	
				if (currentObject->State != STATIC)
				{
					DisplayObjectDebugInfo(currentObject, objCount, GameWorld);
				}
				
				currentObject = currentObject->nextObject;
				objCount--;
			}
		} break;

		default:
		{
			while (currentObject != NULL && objCount > 0)
			{	
				DisplayObjectDebugInfo(currentObject, objCount, GameWorld);
				
				currentObject = currentObject->nextObject;
				objCount--;
			}
		} break;
	}


	return LEMON_SUCCESS;
}


